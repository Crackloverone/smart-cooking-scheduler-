def _run(test_id: str) -> bool:
    """跑一条测试，返回是否**通过**。

    ⚠ 不能把测试文件写死成 `tests/test_deploy_windows.py`：变异目标里还有
      `sync_publish.py`，而盯它的护栏（`test_设备用户层不进发布目录` /
      `test_schedules_user_is_excluded_from_publish`）住在**别的文件**里。
      写死文件前缀时 pytest 会以「no tests ran」退出（**exit 5**），而 exit 5 与
      「断言失败」的 returncode 都非 0 ⇒ 会被当成"护栏命中了" —— 这是**假绿**，
      比漏报还危险（2026-10-08 实测：`recipes_user.json` 那两条变异就在空转）。
      所以：先走快路径，遇到 exit 5 就退化成**全仓库按名字选**。
    """
    env = dict(os.environ)
    env["FT_WIN_DEPLOY_DIR"] = str(SCRATCH)

    def _pytest(args: list[str]) -> subprocess.CompletedProcess:
        return subprocess.run(
            [sys.executable, "-m", "pytest", *args, "-q", "--no-header",
             "-p", "no:cacheprovider"],
            cwd=ROOT, capture_output=True, text=True, encoding="utf-8",
            errors="replace", env=env,
        )

    r = _pytest([f"{TEST_FILE}::{test_id}"])
    if r.returncode == 5:                      # 5 = no tests ran（测试不在这个文件里）
        r = _pytest(["tests/", "-k", test_id])
        if r.returncode == 5:
            raise RuntimeError(
                f"找不到测试 {test_id} —— 变异结果无意义（测试名写错了？）")
    return r.returncode == 0


def main() -> int:
    if SCRATCH.exists():
        shutil.rmtree(SCRATCH, ignore_errors=True)
    SCRATCH.mkdir(parents=True, exist_ok=True)
    for name in list(SCRIPTS) + list(_EXTRA_SRC):
        shutil.copy2(_src_of(name), SCRATCH / name)

    # 先确认"未变异时全绿" —— 否则后面所有变异都会"失败"，看起来 100% 命中，其实是假的
    if not _run("test_script_exists_and_is_not_empty"):
        print("[X] 基线就没过：副本里的脚本读不到或被改坏了，变异结果无意义")
        return 2

    missed: list[str] = []
    skipped: list[str] = []
    print(f"逐条注入 {len(MUTATIONS)} 个变异（只动 .workbuddy-ai/tmp/ 下的副本）")
    print()
    try:
        for label, fname, test_id, mutate in MUTATIONS:
            p = SCRATCH / fname
            orig = _src_of(fname).read_bytes()
            mutated = mutate(orig)                       # type: ignore[operator]
            if mutated == orig:
                skipped.append(label)
                print(f"  [跳过] {label}  —— 锚点在当前文件里找不到（护栏可能已失效，请核对）")
                continue
            p.write_bytes(mutated)
            try:
                passed = _run(test_id)
            finally:
                p.write_bytes(orig)                      # 立刻还原副本
            if passed:
                missed.append(label)
                print(f"  [漏网] {label}  ->  {test_id}")
            else:
                print(f"  [命中] {label}")
    finally:
        shutil.rmtree(SCRATCH, ignore_errors=True)

    print()
    if skipped:
        print(f"⚠ 有 {len(skipped)} 条变异锚点找不到 —— 跳过 = 那条护栏已经没人验了：")
        for s in skipped:
            print("   -", s)
    if missed:
        print(f"✗ 有 {len(missed)} 条变异**没被护栏拦住**（护栏空转）：")
        for m in missed:
            print("   -", m)
        return 1
    if skipped:
        return 3
    print(f"✓ 全部 {len(MUTATIONS)} 条变异都被对应护栏捕获。")
    return 0


if __name__ == "__main__":
    sys.exit(main())
